-- ══════════════════════════════════════════════════════════════════════════
-- جدولة تنظيف الحجوزات المعلّقة (pg_cron)
--
-- الحجوزات المعلّقة (pending_payments) لا تحجز مخزونًا — المخزون يُخصم فقط
-- عند اكتمال الدفع عبر complete_pending_payment. لذا هذه الجدولة هي
-- *تنظيف وصيانة* لإبقاء الجدول مرتبًا ودقة تقارير الحالة، وليست آلية
-- لتحرير مخزون عالق.
--
-- تُشغّل كل 15 دقيقة: تحوّل أي حجز انتهت صلاحيته من 'pending' إلى 'expired'.
-- ══════════════════════════════════════════════════════════════════════════

CREATE EXTENSION IF NOT EXISTS pg_cron;

-- pg_cron 1.4+ (المتوفر في Supabase) يقوم بـ upsert على jobname،
-- فإعادة تشغيل هذا الـ migration آمنة ولا تُنشئ مهامًا مكررة.
SELECT cron.schedule(
  'expire-stale-pending-payments',
  '*/15 * * * *',
  $$ SELECT public.expire_stale_pending_payments(); $$
);
